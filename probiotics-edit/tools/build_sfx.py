"""Write the sound-effect <audio> clips into index.html between the SFX markers.

Each cue is the time its picture lands; the clip starts early by the file's measured peak
(`npx hyperframes audio <file> --json` -> moments.peak) so the hit sounds one frame after it.

    python3 tools/build_sfx.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FRAME = 1 / 30

# file -> (peak seconds, duration seconds, volume)
SFX = {
    "whoosh": (0.162, 0.575, 0.45),
    "whoosh-low": (0.177, 0.672, 0.45),
    "pop": (0.120, 0.72, 1.3),
    "pop-high": (0.101, 0.648, 1.2),
    "click-soft": (0.073, 0.366, 1.5),
    "sparkle": (0.027, 1.802, 0.22),
    "impact-bass-1": (0.073, 2.116, 0.3),
}

# (time the picture lands, sound, what it is for)
CUES = [
    (0.55, "whoosh-low", "lower third wipes in"),
    (3.30, "pop", "? badge"),
    (6.85, "whoosh", "gut scene"),
    (10.65, "sparkle", "good bacteria turn green"),
    (6.60 + 6.3 + 0.1, "pop", "row: digest food"),
    (6.60 + 7.1 + 0.1, "pop-high", "row: protect the gut lining"),
    (6.60 + 8.45 + 0.1, "pop", "row: keep harmful bacteria in check"),
    (17.10, "whoosh-low", "what are probiotics"),
    (16.90 + 2.5 + 0.15, "click-soft", "live microorganisms"),
    (16.90 + 4.75 + 0.15, "click-soft", "in adequate amounts"),
    (16.90 + 6.3 + 0.15, "pop", "a benefit to health"),
    (25.30, "whoosh", "strain scene"),
    (24.80 + 2.2 + 0.1, "pop-high", "important-thing chip"),
    (24.80 + 4.0 + 0.05, "impact-bass-1", "NOT EVERY PROBIOTIC"),
    (31.15, "whoosh-low", "where they help"),
    (30.90 + 1.5 + 0.1, "pop", "can help"),
    (30.90 + 4.25 + 0.1, "pop-high", "may help"),
    (30.90 + 10.85 + 0.1, "click-soft", "uncertain"),
    (42.85, "whoosh", "what can you do"),
    (42.50 + 2.35 + 0.1, "pop", "tile: balanced diet"),
    (42.50 + 3.4 + 0.1, "pop-high", "tile: plenty of fibre"),
    (42.50 + 5.55 + 0.1, "pop", "tile: curd"),
    (42.50 + 6.1 + 0.1, "pop-high", "tile: buttermilk"),
    (49.20 + 1.6, "sparkle", "magic sparkles"),
    (49.20 + 1.95, "click-soft", "cross strikes the pill"),
    (49.20 + 2.6, "whoosh", "right probiotic slides in"),
    (49.20 + 3.55, "whoosh-low", "right condition slides in"),
    (49.20 + 4.1, "pop", "makes all the difference"),
    (54.95, "whoosh", "end card"),
    (54.90 + 1.1, "pop-high", "follow button"),
]


def main():
    rows = []
    for i, (at, name, why) in enumerate(sorted(CUES)):
        peak, dur, vol = SFX[name]
        start = max(0.0, at + FRAME - peak)
        rows.append(
            f'      <audio id="sfx-{i:02d}" class="clip" src="assets/sfx/{name}.mp3" '
            f'data-start="{start:.3f}" data-duration="{dur:.3f}" data-volume="{vol}" '
            f'data-track-index="{11 if dur > 1 else 9 + i % 2}"></audio> <!-- {why} -->'
        )
    page = (ROOT / "index.html").read_text()
    block = "      <!-- SFX:BEGIN (generated by tools/build_sfx.py) -->\n" + "\n".join(rows) + "\n      <!-- SFX:END -->"
    if "SFX:BEGIN" in page:
        page = re.sub(r"      <!-- SFX:BEGIN.*?SFX:END -->", lambda _: block, page, flags=re.S)
    else:
        page = page.replace("    </div>\n\n    <script>", block + "\n    </div>\n\n    <script>", 1)
    (ROOT / "index.html").write_text(page)
    print(f"{len(rows)} cues")


if __name__ == "__main__":
    main()
